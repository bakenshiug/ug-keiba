def process(target):
    name = target["name"]
    path = target["path"]
    confirmed = target["confirmed"]
    oracle = target["oracle"]

    print(f"\n━━━ {name} ━━━")
    notes = json.loads(path.read_text(encoding='utf-8'))

    # 確定馬マップ作成
    confirmed_map = {n: (age, kinryo, joc, sta, odds) for n, age, kinryo, joc, sta, odds in confirmed}
    confirmed_names = set(confirmed_map.keys())

    # 1) horses配列を確定馬のみに絞込
    original_horses = notes.get("horses", [])
    original_names = {h["name"] for h in original_horses}
    kept = []
    removed = []
    for h in original_horses:
        if h["name"] in confirmed_names:
            # 確定馬: 情報上書き
            age, kinryo, joc, sta, odds = confirmed_map[h["name"]]
            h["sexAge"] = age
            h["kinryo"] = kinryo
            h["jockey"] = joc
            h["stable"] = sta
            h["expectedOdds"] = odds
            kept.append(h)
        else:
            removed.append(h["name"])

    # 新規馬(JSONに無かったが確定リストにいる)もあればチェック
    missing_in_json = confirmed_names - original_names
    if missing_in_json:
        print(f"  ⚠ JSON未登録の確定馬: {missing_in_json}")

    # 2) listOrder 五十音順で1..N再付番
    # 五十音順ソート (ヴィサージュの正規化対応済み馬名の単純sort)
    import unicodedata
    kept.sort(key=lambda h: unicodedata.normalize('NFC', h["name"]))
    for i, h in enumerate(kept, 1):
        h["listOrder"] = i

    notes["horses"] = kept

    # 3) raceInfo.headCount
    if "race" in notes:
        notes["race"]["headCount"] = len(kept)
    if "raceInfo" in notes:
        notes["raceInfo"]["headCount"] = len(kept)

    # 4) preparationNote を御神託リッチテキストに置換
    notes["preparationNote"] = oracle

    # 書き戻し
    path.write_text(json.dumps(notes, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"  登録{len(original_horses)}頭 → 確定{len(kept)}頭")
    print(f"  除外: {removed}")
    print(f"  御神託: {oracle.splitlines()[0][:40]}...")
    print(f"  💾 {path.name}")


def main():
    for t in TARGETS:
        process(t)
    print("\n✅ 完了")


if __name__ == "__main__":
    main()
